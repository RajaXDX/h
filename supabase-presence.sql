-- ============================================================================
-- نبضة الحضور في الرومات
-- ============================================================================
--
-- المشكلة: من يُقفل المتصفح لا يمرّ بـ leaveRoom، فيبقى صفّه status='active'
-- إلى الأبد. النتيجة أن مضيفاً غادر فعلياً تظلّ الروم منسوبة إليه: لا توزيع
-- فرق ولا بدء جولة ولا تحكّم، والباقون عالقون.
--
-- الحل: كل لاعب يُحدّث last_seen_at دورياً، ومن تجاوز صمته المهلة يُعدّ غائباً.
--
-- ⚠️ لماذا لا نستخدم beforeunload + leaveRoom بدلاً من هذا:
-- تحديث الصفحة يُطلقه أيضاً، فيصير كل تحديث خروجاً نهائياً وتنكسر ميزة
-- «العودة بعد الانقطاع». النبضة تفرّق بين الغياب والتحديث لأنها تقيس الزمن.
--
-- شغّله مرة واحدة في Supabase → SQL Editor.
-- ============================================================================

ALTER TABLE room_players
  ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ DEFAULT now();

-- الصفوف الموجودة قبل هذا العمود تبدأ حاضرة لا غائبة، وإلا طُرد كل من في
-- الرومات القائمة لحظة التشغيل
UPDATE room_players
  SET last_seen_at = COALESCE(last_seen_at, joined_at, now())
  WHERE last_seen_at IS NULL;

-- البحث عن الغائبين يمرّ دائماً بـ (room_id, status)
CREATE INDEX IF NOT EXISTS idx_room_players_seen
  ON room_players(room_id, status, last_seen_at);

COMMENT ON COLUMN room_players.last_seen_at IS
  'آخر نبضة حضور من جهاز اللاعب. من تجاوز صمته المهلة يُعدّ غائباً وتنتقل استضافته.';
